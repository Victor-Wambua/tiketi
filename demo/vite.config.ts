import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';

const at = (rel: string) => fileURLToPath(new URL(rel, import.meta.url));
const root = at('..').replace(/\/$/, '');

/**
 * Builds the demo: the repo's own server and front-end, with Node built-ins swapped for the
 * browser adapters in `demo/src/shims`. Nothing under `src/` is modified.
 */
const SWAP_FILES = new Map([
  [`${root}/src/server/ticketKeys.ts`, at('./src/shims/ticketKeys.ts')],
  [`${root}/src/server/layouts.ts`, at('./src/shims/layouts.ts')],
]);

// Two server files call `.unref()` on a timer, which only Node timers have.
const UNREF_FILES = [`${root}/src/server/inventory.ts`, `${root}/src/server/payments/mockMpesa.ts`];

function demoAdapters(): Plugin {
  return {
    name: 'tiketi-demo-adapters',
    enforce: 'pre',
    async resolveId(source, importer, options) {
      if (!importer || !(source.startsWith('.') || source.startsWith('/'))) return null;
      const resolved = await this.resolve(source, importer, { ...options, skipSelf: true });
      return (resolved && SWAP_FILES.get(resolved.id)) ?? null;
    },
    transform(code, id) {
      if (!UNREF_FILES.includes(id)) return null;
      const timers = at('./src/shims/timers.ts');
      return `import { setTimeout, setInterval, clearTimeout, clearInterval } from ${JSON.stringify(timers)};\n${code}`;
    },
  };
}

/** A content policy in a meta tag (a static host cannot send headers). Build only: the dev server injects inline styles. */
function contentPolicy(): Plugin {
  return {
    name: 'tiketi-demo-csp',
    apply: 'build',
    transformIndexHtml: () => [
      {
        tag: 'meta',
        attrs: {
          'http-equiv': 'Content-Security-Policy',
          content:
            "default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self'; img-src 'self' data: blob:; connect-src 'self'; media-src 'self' blob:; worker-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'",
        },
        injectTo: 'head-prepend',
      },
    ],
  };
}

/** Writes a service worker that caches every built file, so the demo keeps working with no network after one visit. */
function offlineCache(): Plugin {
  return {
    name: 'tiketi-demo-offline',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = ['./', 'favicon.svg', ...Object.keys(bundle)].sort();
      const version = createHash('sha256').update(files.join('|')).digest('hex').slice(0, 12);
      const source = `/* Generated by the demo build. Caches the demo's own files; never touches other origins. */
const CACHE = 'tiketi-demo-${version}';
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  root: at('.'),
  base: './',
  publicDir: at('./public'),
  plugins: [demoAdapters(), contentPolicy(), offlineCache()],
  define: { 'import.meta.env.VITE_ROUTING': JSON.stringify('hash') },
  resolve: {
    alias: [
      { find: 'node:sqlite', replacement: at('./src/shims/sqlite.ts') },
      { find: 'node:crypto', replacement: at('./src/shims/crypto.ts') },
      { find: /^node:(fs|path|url|events|util)$/, replacement: at('./src/shims/node.ts') },
      { find: 'hono/cookie', replacement: at('./src/shims/cookie.ts') },
      { find: '@hono/node-server/serve-static', replacement: at('./src/shims/serveStatic.ts') },
    ],
  },
  build: { outDir: at('../dist/demo'), emptyOutDir: true, target: 'es2022' },
  server: { fs: { allow: [root] } },
});
